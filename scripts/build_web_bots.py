"""Bundle the bots the Play page offers, and their pinned browser Python runtime.

The bots are those of the bot index, bots/index.json, whose play_page isn't
null. web/bot-index.js tells the page about them (web/bots.js), and
web/reference-bots.zip holds the Python ones and the files they import, for
scripts/browser_bot.py to run with Pyodide.

Usage: python scripts/build_web_bots.py [--skip-runtime]
"""

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import shutil
import tarfile
import urllib.request
import zipfile

VERSION = "0.28.3"
RUNTIME_DIR = f"pyodide-{VERSION}"
INTEGRITY = "rtCsyTU55oNGpLzSVuAd55ZvruJDEX8o6keSdWKN9jPeBVSNlynaKFG7eRqkiIgU7i2M6HEgYtm0atCEQX3u4A=="
# What the page needs to know of each of its bots, besides its id.
PAGE_FIELDS = ("name", "about", "rules", "maps", "play_page")


def build(root):
    runtime(root)
    bundle(root)


def runtime(root):
    """Unpacks Pyodide, the browser's Python, into web/, downloading it once."""
    web = root / "web"
    cache = root / "target" / f"{RUNTIME_DIR}.tgz"
    cache.parent.mkdir(exist_ok=True)
    data = cache.read_bytes() if cache.exists() else b""
    expected = base64.b64decode(INTEGRITY)
    if hashlib.sha512(data).digest() != expected:
        url = f"https://registry.npmjs.org/pyodide/-/{RUNTIME_DIR}.tgz"
        with urllib.request.urlopen(url, timeout=60) as response:
            data = response.read()
        if hashlib.sha512(data).digest() != expected:
            raise ValueError("Unexpected Pyodide package checksum")
        cache.write_bytes(data)

    folder = web / RUNTIME_DIR
    folder.mkdir(exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as package:
        for name in ("pyodide.js", "pyodide.asm.js", "pyodide.asm.wasm", "pyodide-lock.json", "python_stdlib.zip"):
            (folder / name).write_bytes(package.extractfile(f"package/{name}").read())
    shutil.copyfile(root / "scripts" / "pyodide-LICENSE.txt", folder / "LICENSE.txt")


def bot_index(root):
    """The bot index's records, by id, in its order."""
    return json.loads((root / "bots" / "index.json").read_text(encoding="utf-8"))["bots"]


def page_list(bots):
    """The text of web/bot-index.js: the Play page's bots, in the index's order."""
    items = [{"id": bid, **{field: b[field] for field in PAGE_FIELDS}} for bid, b in bots.items() if b["play_page"]]
    rows = ",\n".join("  " + json.dumps(item, ensure_ascii=False) for item in items)
    return ("// Generated by scripts/build_web_bots.py from bots/index.json. Don't edit.\n"
            f"var BitbathBotIndex = [\n{rows}\n];\n"
            'if (typeof module !== "undefined") module.exports = BitbathBotIndex;\n')


def bundled(bots):
    """The files in web/reference-bots.zip, from the repository's root: the
    index, the driver, and the Python bots the page runs, with the files
    they import. The zip has no folders, so no two may share a name."""
    files = ["bots/index.json", "scripts/browser_bot.py"]
    for b in bots.values():
        if b["play_page"] == "pyodide":
            files += [f for f in b["files"] + b["depends"] if f not in files]
    names = [Path(f).name for f in files]
    if len(set(names)) < len(names):
        raise ValueError(f"Two files of the bundle share a name: {files}")
    return files


def bundle(root):
    """Writes web/bot-index.js and web/reference-bots.zip from the bot index."""
    web = root / "web"
    bots = bot_index(root)
    (web / "bot-index.js").write_text(page_list(bots), encoding="utf-8", newline="\n")
    with zipfile.ZipFile(web / "reference-bots.zip", "w") as out:
        for f in bundled(bots):
            out.writestr(zipfile.ZipInfo(Path(f).name), (root / f).read_bytes(), compress_type=zipfile.ZIP_DEFLATED)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--skip-runtime", action="store_true",
                        help="write only bot-index.js and reference-bots.zip, leaving Pyodide as it is")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if not args.skip_runtime:
        runtime(root)
    bundle(root)
