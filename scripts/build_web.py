"""Builds the engine to wasm and embeds it in web/bitbath_wasm.js.

The viewer loads the wasm from that script as base64 instead of fetching a
.wasm file, so web/play.html can open replays straight from disk.

Usage: python scripts/build_web.py [--dist]
"""

import argparse
import base64
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

import build_web_bots

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dist", action="store_true", help="also build the hosted site and game database Worker")
    args = parser.parse_args()
    cargo = shutil.which("cargo") or os.path.expanduser(os.path.join("~", ".cargo", "bin", "cargo"))
    cmd = [cargo, "build", "-p", "bitbath-wasm", "--release", "--target", "wasm32-unknown-unknown"]
    if subprocess.run(cmd, cwd=ROOT).returncode != 0:
        sys.exit("cargo build failed. Is the target installed? rustup target add wasm32-unknown-unknown")
    wasm = os.path.join(ROOT, "target", "wasm32-unknown-unknown", "release", "bitbath_wasm.wasm")
    with open(wasm, "rb") as f:
        data = base64.b64encode(f.read()).decode("ascii")
    out = os.path.join(ROOT, "web", "bitbath_wasm.js")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by scripts/build_web.py from the engine crate. Don't edit.\n")
        f.write('var BITBATH_WASM_BASE64 = "%s";\n' % data)
    print("wrote %s (%d KB)" % (os.path.relpath(out, ROOT), len(data) // 1024))
    build_web_bots.build(Path(ROOT))
    subprocess.run([sys.executable, os.path.join(ROOT, "bench", "leaderboard.py")], check=True)
    if args.dist:
        dist = Path(ROOT, "dist")
        destination = dist / "client"
        destination.mkdir(parents=True, exist_ok=True)
        for name in ("index.html", "humans.html", "play.html", "arena.css", "home.css", "mark.svg", "micro-map.svg",
                     "standings.js", "home.js", "bitbath_wasm.js", "engine.js", "kit.js", "bots.js",
                     "reference-bots.zip", "reference-worker.js", "reference-opponent.js", "astra.js", "astra.wasm",
                     "pieces.js", "sounds.js", "viewer.js", "play.js",
                     "recording.js", "scoreboard.js", "scoreboard-position.js"):
            shutil.copyfile(os.path.join(ROOT, "web", name), os.path.join(destination, name))
            # Remove flat copies produced by the previous static build.
            (dist / name).unlink(missing_ok=True)
        shutil.copytree(Path(ROOT, "web", build_web_bots.RUNTIME_DIR),
                        Path(destination, build_web_bots.RUNTIME_DIR), dirs_exist_ok=True)
        old_runtime = dist / build_web_bots.RUNTIME_DIR
        if old_runtime.is_dir():
            for asset in (destination / build_web_bots.RUNTIME_DIR).iterdir():
                (old_runtime / asset.name).unlink(missing_ok=True)
            if not any(old_runtime.iterdir()):
                old_runtime.rmdir()
        server = dist / "server"
        metadata = dist / ".openai"
        server.mkdir(exist_ok=True)
        metadata.mkdir(exist_ok=True)
        shutil.copyfile(Path(ROOT, "site/worker.mjs"), server / "index.js")
        config = json.loads(Path(ROOT, "site/wrangler.json").read_text(encoding="utf8"))
        config["main"] = "index.js"
        config["assets"]["directory"] = "../client"
        config["d1_databases"][0]["migrations_dir"] = "../.openai/drizzle"
        (server / "wrangler.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf8")
        shutil.copyfile(Path(ROOT, ".openai/hosting.json"), metadata / "hosting.json")
        shutil.copytree(Path(ROOT, "site/drizzle"), metadata / "drizzle", dirs_exist_ok=True)


if __name__ == "__main__":
    main()
