"""Rate the bots of the bot index, ladder by ladder, into bots/ratings.json.

A rating means something only against the bots it was won from, on one map,
so each ladder keeps its own (README: Ratings):

- micro: the benchmark's newest Micro arena season, the one the homepage's
  standings show. The reference bots and the entries play there.
- islets, islands: the bots that know the strategic rules and are made for
  the map play each other on it here, with bitbath tournament.

A rating keeps the hash of each file it was won with: the bot's files and
what they import, or a benchmark entry's submission. Once one of them
changes, the rating is stale until its ladder is played again. A ladder
keeps its config's hash too, and is stale as a whole once that changes.

Usage:
  python scripts/ratings.py            show the ratings, and which are stale
  python scripts/ratings.py micro      take the micro ladder from the arena
  python scripts/ratings.py islets [--jobs <n>] [--bitbath <path>]
                                       play a ladder here, and keep its ratings
"""

import argparse
import datetime
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from bench.leaderboard import newest_season  # noqa: E402

INDEX = ROOT / "bots" / "index.json"
RATINGS = ROOT / "bots" / "ratings.json"
EXE = ".exe" if sys.platform == "win32" else ""
DOC = ("Generated by scripts/ratings.py, which README.md describes under \"Ratings\": the bots of the index, "
       "rated ladder by ladder. A rating keeps the hash of each file it was won with, and a ladder its "
       "config's, and each is stale once one of them changes.")

LADDERS = {
    "micro": {
        "about": "The benchmark's newest Micro arena season: the reference bots and the entries.",
        "rules": "classic", "map": "micro",
    },
    "islets": {
        "about": "The bots that know the strategic rules and are made for Islets, each pair on every seed, "
                 "both ways round.",
        "rules": "strategic", "map": "islets", "config": "configs/islets.toml", "seeds": "1-20",
        "anchor": "supply=1000",
    },
    "islands": {
        "about": "The bots that know the strategic rules and are made for Islands, each pair on every seed, "
                 "both ways round.",
        "rules": "strategic", "map": "islands", "config": "configs/islands.toml", "seeds": "1-20",
        "anchor": "supply=1000",
    },
}
# What a rating keeps of the runner's ratings.json, besides its source.
STATS = ("rating", "interval", "games", "wins", "draws", "losses", "forfeits", "invalid_pct", "avg_think_ms",
         "max_think_ms")


def sha256(data):
    """A file's hash, with its line endings as git keeps them."""
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, check=True).stdout


def source(bot):
    """What a bot is made of now, as {path: hash}: its files and what they
    import, or a benchmark entry's submission, whose hash the index keeps."""
    session = bot["made"].get("session")
    if bot["kind"] == "entry" and session:
        return {f"entries/{session['entry']}/submission.tar": session["submission_sha256"]}
    return hashes(bot["files"] + bot["depends"])


def hashes(paths):
    """{path: hash} for files as they are now. A file that's gone has none."""
    return {p: sha256((ROOT / p).read_bytes()) for p in paths if (ROOT / p).is_file()}


def changed(was, now):
    """The files that a rating or ladder was played with and that aren't as they were."""
    return sorted(f for f in was.keys() | now.keys() if was.get(f) != now.get(f))


def plays(bot, ladder):
    """Whether a bot knows a ladder's rules, and is made for its map."""
    return ladder["rules"] in bot["rules"] and (bot["maps"] == "any" or ladder["map"] in bot["maps"])


def rating(row, files):
    return {key: row[key] for key in STATS} | {"source": files}


def from_arena(index):
    """The micro ladder, from the newest Micro arena season (bench/arena.py)."""
    found = newest_season(ROOT)
    if not found:
        sys.exit("There's no Micro arena season in arena/, which isn't in git: bench/arena.py plays them.")
    season, state, scores = found
    commit, kit = state["kit_commit"], state["settings"]["kit"]
    ratings = {}
    for row in scores["ratings"]:
        name = row["bot"]
        if name not in index:
            continue
        bot = state["bots"][name]
        if bot["kind"] == "entry":
            files = {f"entries/{bot['source']}/submission.tar": bot["sha256"]}
        else:
            # The arena plays a reference bot as its file and the kit were in
            # the commit its image was built from.
            files = {path: sha256(git("show", f"{commit}:{path}")) for path in (bot["source"], kit)}
        ratings[name] = rating(row, files)
    maps = state["settings"]["maps"]
    return {
        **{key: LADDERS["micro"][key] for key in ("about", "rules", "map")},
        "config": {m["config"]: sha256(git("show", f"{commit}:{m['config']}")) for m in maps},
        "from": f"arena season {season.name}",
        "date": state["updated"][:10],
        "commit": commit[:7],
        "seeds": ", ".join(m["seeds"] for m in maps),
        "games": scores["games"],
        "anchor": scores["anchor"],
        "field": [row["bot"] for row in scores["ratings"]],
        "ratings": ratings,
    }


def command(bot, built):
    """The command that runs a bot here: a Python bot with this Python, and a
    Rust bot built afresh into `built`, so target/release is left alone."""
    if bot["language"] == "python":
        return f'"{sys.executable}" {bot["run"].split(None, 1)[1]}'
    built.mkdir(parents=True, exist_ok=True)
    exe = built / (Path(bot["files"][0]).stem + EXE)
    subprocess.run(["rustc", "-O", bot["files"][0], "-o", str(exe)], cwd=ROOT, check=True)
    return f'"{exe}"'


def check_bitbath(path):
    """Refuses a bitbath built before the engine's or runner's source last
    changed: its games could follow rules the repository no longer has."""
    if not path.is_file():
        sys.exit(f"There's no {path}: build it with cargo build --release, or name one with --bitbath.")
    newest = max(f.stat().st_mtime for part in ("engine", "runner") for f in (ROOT / part).rglob("*") if f.is_file())
    if path.stat().st_mtime < newest:
        sys.exit(f"{path} is older than the engine's or runner's source: rebuild it with cargo build --release.")


def play(name, index, jobs, bitbath):
    """Plays a ladder with bitbath tournament, and returns it rated."""
    spec = LADDERS[name]
    field = {bid: b for bid, b in index.items()
             if plays(b, spec) and b["run"] and b["language"] in ("python", "rust")}
    if len(field) < 2:
        sys.exit(f"{name} needs two bots that play it, and has {len(field)}.")
    check_bitbath(bitbath)
    files = {bid: source(b) for bid, b in field.items()}
    config = hashes([spec["config"]])
    # The ladder records the commit it was played at, so what it rates must
    # be in that commit, and not someone's work in progress.
    edits = git("status", "--porcelain", "--", *sorted({f for s in files.values() for f in s} | set(config)))
    if edits.strip():
        sys.exit("Commit these first, so the ladder rates what's in the commit:\n" + edits.decode())
    out = ROOT / "runs" / "ladders" / f"{name}-{datetime.datetime.now():%Y%m%d-%H%M%S}"
    args = [str(bitbath), "tournament"]
    for bid, b in field.items():
        args += ["--bot", f"{bid}={command(b, out / 'bin')}"]
    args += ["--config", spec["config"], "--seeds", spec["seeds"], "--anchor", spec["anchor"],
             "--jobs", str(jobs), "--out", str(out)]
    subprocess.run(args, cwd=ROOT, check=True)
    if any(source(b) != files[bid] for bid, b in field.items()) or hashes(config) != config:
        sys.exit("A bot's files or the config changed while the games ran, so they rate neither version: "
                 "play the ladder again.")
    scores = json.loads((out / "ratings.json").read_text(encoding="utf-8"))
    return {
        **{key: spec[key] for key in ("about", "rules", "map")},
        "config": config,
        "from": "bitbath tournament",
        "date": datetime.date.today().isoformat(),
        "commit": git("rev-parse", "--short", "HEAD").decode().strip(),
        "seeds": spec["seeds"],
        "games": scores["games"],
        "anchor": scores["anchor"],
        "field": [row["bot"] for row in scores["ratings"]],
        "ratings": {row["bot"]: rating(row, files[row["bot"]]) for row in scores["ratings"]},
    }


def load():
    ratings = json.loads(RATINGS.read_text(encoding="utf-8")) if RATINGS.is_file() else {"ladders": {}}
    return {"doc": DOC, "ladders": ratings["ladders"]}


def write(ratings):
    ratings["ladders"] = {name: ratings["ladders"][name] for name in LADDERS if name in ratings["ladders"]}
    text = json.dumps(ratings, indent=2, ensure_ascii=False)
    # A list of numbers or names goes on one line, as in the index.
    text = re.sub(r"\[\n\s+([^\[\]{}]*?)\n\s*\]",
                  lambda m: "[" + ", ".join(line.strip().rstrip(",") for line in m.group(1).split("\n")) + "]", text)
    RATINGS.write_text(text + "\n", encoding="utf-8", newline="\n")


def report(index, ratings):
    """Prints each ladder's ratings, saying which are stale and why."""
    for name, ladder in ratings["ladders"].items():
        anchor = ladder["anchor"]
        scale = f"{anchor['bot']} = {anchor['rating']:.0f}" if anchor else "averaging 1500"
        print(f"{name}: {ladder['rules']} rules on {ladder['map']}, from {ladder['from']} on {ladder['date']}, "
              f"{ladder['games']} games, {scale}")
        gone = changed(ladder["config"], hashes(ladder["config"]))
        if gone:
            print(f"  All stale: {', '.join(gone)} changed since")
        width = max(len(bid) for bid in ladder["ratings"])
        print(f"  {'bot':<{width}}  rating  95% interval  games     W     D     L  invalid  avg ms  source")
        for bid, r in ladder["ratings"].items():
            gone = changed(r["source"], source(index[bid])) if bid in index else ["no longer in the index"]
            low, high = r["interval"] or (r["rating"], r["rating"])
            print(f"  {bid:<{width}}  {r['rating']:>6.0f}  {f'{low:.0f}..{high:.0f}':>12}  {r['games']:>5} "
                  f"{r['wins']:>5} {r['draws']:>5} {r['losses']:>5}  {r['invalid_pct']:>6.1f}%  "
                  f"{r['avg_think_ms']:>6.0f}  {'stale: ' + ', '.join(gone) + ' changed' if gone else 'current'}")
        unrated = [bid for bid, b in index.items() if plays(b, ladder) and bid not in ladder["ratings"]]
        if unrated:
            print(f"  Not rated here, though they play it: {', '.join(unrated)}")
        print()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("ladder", nargs="?", choices=LADDERS, help="the ladder to rate again")
    parser.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) // 2),
                        help="games to play at once (default: half the cores)")
    parser.add_argument("--bitbath", type=Path, default=ROOT / "target" / "release" / f"bitbath{EXE}",
                        help="the bitbath to play the games with (default: target/release's)")
    args = parser.parse_args()
    index = json.loads(INDEX.read_text(encoding="utf-8"))["bots"]
    ratings = load()
    if args.ladder:
        ratings["ladders"][args.ladder] = (from_arena(index) if args.ladder == "micro"
                                           else play(args.ladder, index, args.jobs, args.bitbath.resolve()))
        write(ratings)
    report(index, ratings)


if __name__ == "__main__":
    main()
